import type { GameAccountField, GameTopUp, GameTopUpPackage } from "@/types/game-top-up";

function packages(
  gameId: string,
  currency: string,
  values: Array<[number, string, number?]>,
): GameTopUpPackage[] {
  return values.map(([coinAmount, priceBdt, bonusAmount = 0], index) => ({
    id: `${gameId}-package-${index + 1}`,
    gameId,
    name: `${coinAmount}${bonusAmount ? ` + ${bonusAmount}` : ""} ${currency}`,
    coinAmount,
    bonusAmount,
    priceBdt,
    isActive: true,
    isPopular: index === 1,
    sortOrder: index,
    stockQuantity: null,
  }));
}

function playerFields(gameId: string, includeServer = false): GameAccountField[] {
  return [
    {
      id: `${gameId}-player-id`,
      gameId,
      key: "playerId",
      label: "Player ID",
      type: "TEXT",
      placeholder: "Enter your in-game player ID",
      helpText: "Use the identifier shown in your game profile.",
      required: true,
      options: [],
      validationRules: { minLength: 4, maxLength: 32 },
      isActive: true,
      sortOrder: 0,
    },
    ...(includeServer
      ? [{
          id: `${gameId}-server`,
          gameId,
          key: "server",
          label: "Server / Zone",
          type: "SELECT" as const,
          placeholder: null,
          helpText: "Select the server connected to your player ID.",
          required: true,
          options: [
            { label: "Asia", value: "asia" },
            { label: "Europe", value: "europe" },
            { label: "America", value: "america" },
          ],
          validationRules: {},
          isActive: true,
          sortOrder: 1,
        }]
      : []),
  ];
}

